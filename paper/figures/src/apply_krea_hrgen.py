"""Krea-195 and HRGen-1K (1000 prompts) into main.tex: the HRGen-1K column of Table tab:phase2_general and the
prompt-count macros. Every value is read from results/ (paired_bootstrap.py, 2000 prompt draws, seed 0) through
data195.pairs and formatted by gen_tables.py; nothing is typed by hand. The HRGen-1K and Krea rows of Table
tab:generality used to be patched here; gen_main_tables.py now writes them from the same two CSVs into
figures/snippets/main_tables/tab_generality.tex, which main.tex inputs.

  results/hrgen1k_dev/sca_nb_vs_area.csv   SCA minus AReA, FLUX.1-dev, all 1000 HRGen-1K prompts
  results/krea195/sca_krea_vs_area.csv     SCA minus AReA, FLUX.1-Krea-dev, all 195 Aesthetic-4K prompts

Table tab:krea_6144 is regenerated by gen_late_tables.krea_6144_table() (called from here) and Table
tab:published_compare by results/published_compare/build.py. Idempotent; prints every change.
Run: <sca env python> apply_krea_hrgen.py
"""
import ast
import csv
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
MAIN = ROOT / "paper" / "main.tex"
sys.path.insert(0, str(SRC))
import data195  # noqa: E402

# gen_tables.py's formatting helpers (f, dcell, MET, METD) without running its table generation
tree = ast.parse((SRC / "gen_tables.py").read_text())
body = [n for n in tree.body if (isinstance(n, ast.FunctionDef) and n.name in {"f", "dcell"})
        or (isinstance(n, ast.Assign) and any(getattr(t, "id", None) in ("MET", "METD") for t in n.targets))]
ns = {}
exec(compile(ast.Module(body=body, type_ignores=[]), "gen_tables.py", "exec"), ns)

LAB = [("ImageReward", "ir"), ("Aesthetic", "aesthetic"), ("CLIP score", "clip"), ("PickScore", "pickscore"),
       ("HPSv2 ($\\times100$)", "hpsv2"), ("HPSv2.1 ($\\times100$)", "hpsv21"), ("MUSIQ", "musiq"),
       ("MUSIQ$_\\text{c}$", "musiq_crop1024"), ("CLIP-IQA ($\\times100$)", "clipiqa"), ("ARNIQA ($\\times100$)", "arniqa")]


def n_pairs(run, a, b):
    ns_ = {r["n_prompts"] for r in csv.DictReader(open(ROOT / "results" / run / f"{a}_vs_{b}.csv"))}
    assert len(ns_) == 1, (run, ns_)
    return int(ns_.pop())


def main():
    tex = MAIN.read_text()
    have_hrgen = (ROOT / "results/hrgen1k_dev/sca_nb_vs_area.csv").exists()
    have_krea = (ROOT / "results/krea195/sca_krea_vs_area.csv").exists()
    if have_hrgen:
        assert n_pairs("hrgen1k_dev", "sca_nb", "area") == 1000
        H = data195.pairs("hrgen1k_dev", "sca_nb", "area")
        # Table tab:phase2_general, HRGen-1K column (second cell)
        s = tex.index("\\label{tab:phase2_general}"); e = tex.index("\\end{tabular}", s)
        blk = tex[s:e]
        for lab, m in LAB:
            line = next(l for l in blk.split("\n") if l.startswith(lab + " & "))
            cells = line[:-len(" \\\\")].split(" & ")
            assert len(cells) == 5, line
            new = " & ".join([cells[0], ns["dcell"](H[m], m)] + cells[2:]) + " \\\\"
            if new != line:
                print("K.3", lab, cells[1], "->", new.split(" & ")[1])
            blk = blk.replace(line, new)
        tex = tex[:s] + blk + tex[e:]
        tex = tex.replace("\\newcommand{\\nhrgen}{200}", "\\newcommand{\\nhrgen}{1000}")
    if have_krea:
        assert n_pairs("krea195", "sca_krea", "area") == 195
        K = data195.pairs("krea195", "sca_krea", "area")
        tex = tex.replace("\\newcommand{\\nkrea}{100}", "\\newcommand{\\nkrea}{195}")
    MAIN.write_text(tex)
    # report the per-image wins for the text (2000 draws)
    for name, P in (("HRGen-1K", H if have_hrgen else None), ("Krea-195", K if have_krea else None)):
        if P:
            better = [m for _, m in LAB if P[m][1] > 0]
            worse = [m for _, m in LAB if P[m][2] < 0]
            print(f"{name}: significantly better on {len(better)} of 10 per-image metrics {better}; worse on {worse}; "
                  f"IR {P['ir']}")


if __name__ == "__main__":
    main()
