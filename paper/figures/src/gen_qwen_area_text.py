"""\\qwenResult for Section 4.4 (optional snippet; main.tex uses it only when \\resqwentrue): one or two sentences with
the numbers of results/qwen_5312_vs_area (scripts/qwen_area_eval.py, HANDOVER Section 38), single-pass SCA against
AReA's released Qwen-Image code at its own settings (40 steps) on Qwen-Image at 5312^2, with SCA both at the same 40 steps
(step-matched) and at Qwen-Image's default 50; seconds are the step-matched medians of timing_step_matched.csv.

A metric counts as a win when its 95% bootstrap interval of SCA minus AReA lies above zero and as a loss when it lies
below; the ten per-image metrics are the project's (ImageReward, HPSv2, HPSv2.1, PickScore, aesthetic, CLIP score,
CLIP-IQA, ARNIQA, MUSIQ, MUSIQ on crops). Seconds are the clean medians of timing_summary.csv (no other process on the
GPU). Writes paper/figures/snippets/qwen_result_text.tex; prints the sentence.
Run with the sca env python:  python paper/figures/src/gen_qwen_area_text.py [--results DIR] [--paper DIR]
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
METRICS = ("ir", "hpsv2", "hpsv21", "pickscore", "aesthetic", "clip", "clipiqa", "arniqa", "musiq_4096", "musiq_crop1024")
NAMES = {"ir": "ImageReward", "hpsv2": "HPSv2", "hpsv21": "HPSv2.1", "pickscore": "PickScore", "aesthetic": "aesthetic",
         "clip": "CLIP score", "clipiqa": "CLIP-IQA", "arniqa": "ARNIQA", "musiq_4096": "MUSIQ",
         "musiq_crop1024": "MUSIQ on crops"}
WORDS = "none one two three four five six seven eight nine ten".split()


def num(x: float) -> str:
    s = f"{x:.3f}" if abs(x) < 10 else f"{x:.2f}"
    return ("+" if x > 0 else "") + s


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--results", type=Path, default=ROOT / "results" / "qwen_5312_vs_area")
    ap.add_argument("--paper", type=Path, default=ROOT / "paper")
    a = ap.parse_args()
    def load(name):
        f = a.results / name
        return {r["metric"]: r for r in csv.DictReader(open(f))} if f.exists() else {}

    def tally(pairs):
        rows = [pairs[m] for m in METRICS if m in pairs]
        if len(rows) != len(METRICS):
            raise SystemExit(f"missing metrics: {sorted(set(METRICS) - set(pairs))}")
        win = [r["metric"] for r in rows if float(r["ci_low"]) > 0]
        loss = [r["metric"] for r in rows if float(r["ci_high"]) < 0]
        lost = " (" + ", ".join(NAMES[m] for m in loss) + ")" if loss else ""
        ir = pairs["ir"]
        return (int(rows[0]["n_prompts"]), f"wins {WORDS[len(win)]} and loses {WORDS[len(loss)]}{lost}",
                f"$%s$ $[%.3f,%.3f]$" % (num(float(ir["delta"])), float(ir["ci_low"]), float(ir["ci_high"])))

    p50, p40 = load("sca_minus_area_5312.csv"), load("sca40_minus_area_5312.csv")
    if not p50:
        raise SystemExit("no sca_minus_area_5312.csv yet")
    n, t50, ir50 = tally(p50)
    if p40:
        n40, t40, ir40 = tally(p40)
        s = (r"Against AReA's released Qwen-Image code at its own settings (40 steps), single-pass \sca{} at $5312^2$ "
             r"over %d prompts %s of ten per-image metrics at the same 40 steps and %s at Qwen-Image's default 50 "
             r"steps; ImageReward differs by %s and %s." % (n40, t40, t50, ir40, ir50))
    else:
        s = (r"Against AReA's released Qwen-Image code at its own settings, single-pass \sca{} at $5312^2$ %s of ten "
             r"per-image metrics over %d prompts; ImageReward differs by %s." % (t50, n, ir50))
    matched = a.results / "timing_step_matched.csv"
    med = next((r for r in csv.DictReader(open(matched)) if r["prompt_id"] == "median"), None) if matched.exists() else None
    if med and med.get("sca40_seconds") and med.get("area_seconds"):
        s += (r" At the same 40 steps a $5312^2$ image takes %d~s with \sca{} and %d~s with AReA on one GH200."
              % (round(float(med["sca40_seconds"])), round(float(med["area_seconds"]))))
    out = a.paper / "figures" / "snippets" / "qwen_result_text.tex"
    out.write_text("% Generated by paper/figures/src/gen_qwen_area_text.py from results/qwen_5312_vs_area; do not edit "
                   "by hand.\n% Used only when main.tex sets \\resqwentrue.\n\\newcommand{\\qwenResult}{" + s + "}\n")
    print(f"wrote {out}:\n{s}")


if __name__ == "__main__":
    main()
