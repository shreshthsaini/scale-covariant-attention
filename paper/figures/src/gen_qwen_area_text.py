"""\\qwenResult for Section 4.4 (optional snippet; main.tex uses it only when \\resqwentrue): one or two sentences with
the numbers of results/qwen_5312_vs_area (scripts/qwen_area_eval.py, HANDOVER Section 38), single-pass SCA against
AReA's released Qwen-Image code at its own settings on Qwen-Image at 5312^2.

A metric counts as a win when its 95% bootstrap interval of SCA minus AReA lies above zero and as a loss when it lies
below; the ten per-image metrics are the project's (ImageReward, HPSv2, HPSv2.1, PickScore, aesthetic, CLIP score,
CLIP-IQA, ARNIQA, MUSIQ, MUSIQ on crops). Seconds are the clean medians of timing_summary.csv (no other process on the
GPU). Writes paper/figures/snippets/qwen_result_text.tex; prints the sentence.
Run with the sca env python:  python paper/figures/src/gen_qwen_area_text.py [--results DIR] [--paper DIR]
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
METRICS = ("ir", "hpsv2", "hpsv21", "pickscore", "aesthetic", "clip", "clipiqa", "arniqa", "musiq_4096", "musiq_crop1024")
NAMES = {"ir": "ImageReward", "hpsv2": "HPSv2", "hpsv21": "HPSv2.1", "pickscore": "PickScore", "aesthetic": "aesthetic",
         "clip": "CLIP score", "clipiqa": "CLIP-IQA", "arniqa": "ARNIQA", "musiq_4096": "MUSIQ",
         "musiq_crop1024": "MUSIQ on crops"}
WORDS = "none one two three four five six seven eight nine ten".split()


def num(x: float) -> str:
    s = f"{x:.3f}" if abs(x) < 10 else f"{x:.2f}"
    return ("+" if x > 0 else "") + s


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--results", type=Path, default=ROOT / "results" / "qwen_5312_vs_area")
    ap.add_argument("--paper", type=Path, default=ROOT / "paper")
    a = ap.parse_args()
    pairs = {r["metric"]: r for r in csv.DictReader(open(a.results / "sca_minus_area_5312.csv"))}
    timing = {r["method"]: r for r in csv.DictReader(open(a.results / "timing_summary.csv")) if r["res"] == "5312x5312"}
    rows = [pairs[m] for m in METRICS if m in pairs]
    if len(rows) != len(METRICS):
        raise SystemExit(f"missing metrics: {sorted(set(METRICS) - set(pairs))}")
    n = int(rows[0]["n_prompts"])
    win = [r["metric"] for r in rows if float(r["ci_low"]) > 0]
    loss = [r["metric"] for r in rows if float(r["ci_high"]) < 0]
    ir = pairs["ir"]
    ir_word = "better" if "ir" in win else ("worse" if "ir" in loss else "unresolved")
    lost = ""
    if loss:
        lost = " (" + ", ".join(NAMES[m] for m in loss) + ")"
    s = (r"Against AReA's released Qwen-Image code at its own settings, single-pass \sca{} at $5312^2$ wins %s of ten "
         r"per-image metrics over %d prompts and loses %s%s; ImageReward is %s ($%s$ $[%s,%s]$)."
         % (WORDS[len(win)], n, WORDS[len(loss)], lost, ir_word, num(float(ir["delta"])),
            f"{float(ir['ci_low']):.3f}", f"{float(ir['ci_high']):.3f}"))
    ts, ta = timing.get("qwen_sca"), timing.get("qwen_area")
    if ts and ta and ts.get("median_seconds_clean") and ta.get("median_seconds_clean"):
        xs, xa = float(ts["median_seconds_clean"]), float(ta["median_seconds_clean"])
        s += (r" A $5312^2$ image takes %d~s with \sca{} (%s steps) and %d~s with AReA (%s steps) on one GH200."
              % (round(xs), ts["steps"], round(xa), ta["steps"]))
    out = a.paper / "figures" / "snippets" / "qwen_result_text.tex"
    out.write_text("% Generated by paper/figures/src/gen_qwen_area_text.py from results/qwen_5312_vs_area; do not edit "
                   "by hand.\n% Used only when main.tex sets \\resqwentrue.\n\\newcommand{\\qwenResult}{" + s + "}\n")
    print(f"wrote {out}:\n{s}")


if __name__ == "__main__":
    main()
