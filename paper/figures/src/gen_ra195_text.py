"""Result sentence of the "measured hand-off" paragraph (main.tex switch \\ifresra), from results/ra195/.

The method agent's single-pass sampler variant lands in results/ra195/ (paired files in the format of
results/prog195_sca_v2/sca_v2_prog_vs_*.csv: method,reference,metric,delta,ci_low,ci_high,n_prompts,...). This script
does nothing until that folder has SHA256SUMS. Then it writes paper/figures/snippets/ra195_text.tex with

  \\raResult   one sentence: the variant minus single-pass SCA (reference sca_v2) on ImageReward, HPSv2.1 (x100),
               PickScore and MUSIQ on 1024^2 crops, each with its 95% paired interval, over n prompts; and, when a
               file with reference area exists, the same four against AReA.

The paragraph's method sentences come from the method agent in paper/figures/snippets/ra195_method.tex, which defines
\\raMethod (one or two sentences, no numbers). main.tex prints the paragraph only with \\resratrue, and only once both
files exist. Every number is read here; nothing is typed.

Run from the repository root: <sca env python> -I paper/figures/src/gen_ra195_text.py
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "results" / "ra195"
OUT = ROOT / "paper" / "figures" / "snippets" / "ra195_text.tex"
# (metric, scale, decimals, name in the sentence)
METRICS = [("ir", 1, 2, "ImageReward"), ("hpsv21", 100, 2, r"HPSv2.1 ($\times100$)"),
           ("pickscore", 1, 2, "PickScore"), ("musiq_crop1024", 1, 1, r"MUSIQ$_\text{c}$")]


def fmt(v, d):
    s = f"{v:+.{d}f}"
    return "$" + ("{-}" + s[1:] if s.startswith("-") else s) + "$"


def interval(lo, hi, d):
    a, b = f"{lo:.{d}f}", f"{hi:.{d}f}"
    return "$[" + a.replace("-", "{-}") + "," + b.replace("-", "{-}") + "]$"


def load():
    pairs = {}
    for path in sorted(SRC.glob("*.csv")):
        rows = list(csv.DictReader(open(path)))
        if not rows or not {"method", "reference", "metric", "delta", "ci_low", "ci_high"} <= set(rows[0]):
            continue
        for r in rows:
            d = pairs.setdefault((r["method"], r["reference"]), {"n": r.get("n_prompts", "")})
            d[r["metric"]] = (float(r["delta"]), float(r["ci_low"]), float(r["ci_high"]))
    return pairs


def clause(dd):
    parts = [f"{name} by {fmt(sc * dd[k][0], d)} {interval(sc * dd[k][1], sc * dd[k][2], d)}"
             for k, sc, d, name in METRICS]
    return ", ".join(parts[:-1]) + ", and " + parts[-1]


def main():
    if not (SRC / "SHA256SUMS").exists():
        print(f"waiting: {SRC / 'SHA256SUMS'} does not exist; nothing written")
        return 0
    pairs = load()
    full = {k: v for k, v in pairs.items() if all(m in v for m, *_ in METRICS)}
    vs_sca = [(k, v) for k, v in full.items() if k[1] == "sca_v2"]
    vs_area = [(k, v) for k, v in full.items() if k[1] == "area"]
    if len(vs_sca) != 1:
        print(f"expected exactly one variant against sca_v2 in {SRC}, found {[k for k, _ in vs_sca]}")
        return 1
    (method, _), dd = vs_sca[0]
    text = rf"Over {dd['n']} prompts at $4096^2$ it changes {clause(dd)} against single-pass \sca{{}}"
    area = [v for (m, _), v in vs_area if m == method]
    if area:
        text += rf", and {clause(area[0])} against AReA"
    lines = ["% Generated by paper/figures/src/gen_ra195_text.py from results/ra195/; do not edit by hand.",
             f"% variant {method}; paired 95% intervals as in results/ra195/*.csv",
             rf"\newcommand{{\raResult}}{{{text}.}}"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
