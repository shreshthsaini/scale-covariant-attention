def clean_seconds():
    """{method: median clean batch-1 seconds per image at 4096^2 on one GH200}.

    results/latency_curve_summary.csv, median_seconds (the audited sweep: full attention, AReA, SCA; three timed
    prompts after a warm-up image), checked against its per-image rows in results/latency_curve.csv. HRDiT, which
    the sweep lacks: median of its hrdit_dev_author rows in results/latency_curve_batch1.csv, which has no HRDiT
    warm-up row, so its cold first run is included (as the Table 1 caption says)."""
    per = {}
    for r in rows("latency_curve.csv"):
        if r["res"] == RES4K:
            check(r["warmup_verified"] == "True", f"latency_curve.csv: unverified warm-up {r}")
            per.setdefault(r["method"], []).append(float(r["seconds"]))
    out = {}
    for r in rows("latency_curve_summary.csv"):
        if r["res"] == RES4K:
            m, med = r["method"], float(r["median_seconds"])
            assert int(r["n"]) == len(per[m]) == 3 and abs(statistics.median(per[m]) - med) < 1e-9, (m, per[m])
            out[m] = med
    hrdit = [float(r["seconds"]) for r in rows("latency_curve_batch1.csv")
             if r["res"] == RES4K and r["method"] == "hrdit_dev_author"]
    assert len(hrdit) == 3, hrdit
    out["hrdit_dev_author"] = statistics.median(hrdit)
    return out


def load_runs():
    runs = {}
    for run in (MAIN_RUN, PANEL_RUN):
        check(data195.n_prompts(run) == {195}, f"results/{run}: prompt counts {data195.n_prompts(run)}, main.tex "
                                               r"says \nmain = \npanel = 195")
        S, D, ref, corrected_ci = data195.load(run)
        assert ref == REF and corrected_ci, f"results/{run}: reference {ref}, corrected_fidp_ci {corrected_ci}"
        runs[run] = (S, D)
    return runs


def panel_marks(method, D):
    """Table 2 marks against 28-step SCA (see the module docstring)."""
    P = data195.pairs(PANEL_RUN, method, REF)
    marks = {}
    for k in PER_IMAGE_COLS:
        _, lo, hi = P[k]
        marks[k] = PLUS if lo > 0 else (CIRC if hi >= 0 else "")
    for k in DIST_COLS:
        _, lo, hi = D[(method, k)]
        assert lo is not None and hi is not None, (method, k)
        marks[k] = PLUS if hi < 0 else ("" if lo > 0 else CIRC)
    return marks


def plain_cells(group, runs, clean):
    """Unmarked cells of Tables 1 and 2, one list per (run, method, label, steps) row."""
    return [[(num(clean[m], d) if m in clean else "n/m") if k == "clean" else num(sc * runs[run][0][(m, k)], d)
             for k, sc, d, _ in COLS] for run, m, _, _ in group]


def table12(spec, runs, clean, underline, marked):
    flat = [(run, m, label, steps) for _, group in spec for run, m, label, steps in group]
    cells = plain_cells(flat, runs, clean)
    for j, (_, _, _, lower) in enumerate(COLS):
        for i, r in ranks([c[j] for c in cells], lower).items():
            if r == "best":
                cells[i][j] = rf"\textbf{{{cells[i][j]}}}"
            elif underline:
                cells[i][j] = rf"\underline{{{cells[i][j]}}}"
    if marked:
        for i, (run, m, _, _) in enumerate(flat):
            if m != REF:
                mk = panel_marks(m, runs[run][1])
                for j, (k, *_) in enumerate(COLS):
                    cells[i][j] += mk.get(k, "")
    body, i = [], 0
    for g, (heading, group) in enumerate(spec):
        body += ([r"\midrule"] if g else []) + [rf"\multicolumn{{11}}{{@{{}}l}}{{\emph{{{heading}}}}} \\"]
        for run, m, label, steps in group:
            body.append((SHADE if m in SHADED else "") + " & ".join([label, steps] + cells[i]) + r" \\")
            i += 1
    return tabular(r"\setlength{\tabcolsep}{3.1pt}", r"@{}lcrr*{7}{r<{\hspace{3pt}}}@{}", HEAD12 + [r"\midrule"],
                   body, "  ")


