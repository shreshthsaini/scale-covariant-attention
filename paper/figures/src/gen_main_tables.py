"""Main-text Tables 1 to 4 and the headline numbers of the prose, generated from results/ (nothing typed by hand).

One command, run from the repository root, regenerates all five files:

    PATH=$HOME/.local/bin:$PATH UV_CACHE_DIR=/work/09032/saini_2/vista/library/uv-cache uv run --no-project \
        --python /work/09032/saini_2/vista/library/uv-envs/sca/bin/python python paper/figures/src/gen_main_tables.py

Outputs, in paper/figures/snippets/main_tables/:
  tab_main.tex, tab_panel46.tex, tab_ablation.tex, tab_generality.tex
      the \\setlength{\\tabcolsep} line and the tabular of Tables tab:main, tab:panel46, tab:ablation and
      tab:generality. The float, caption, label and font line stay in main.tex, which \\input's the file in place
      of the tabular. Each file ends in "\\end{tabular}%" so the \\input adds no extra space.
  headline.tex
      \\newcommand{\\hl...} macros for the numbers that the abstract, introduction, Section 4.1 and the
      conclusion repeat; \\input it once in the preamble. A comment above each macro names its CSV and column.

Inputs: results/*.csv only (the a4k195_* runs through data195.py), plus one archived JSON for the ablation
table's Err. column, which no CSV holds: results/evidence/calib/k1_1024.json, scales/4/rel_err (the calibration
report that k1data.py checks; paper/figures/src/data/k1_1024.json is a copy).

Rules, all set below rather than typed into the cells:
  * numbers use Python's format() at each column's precision; a negative value is set in math mode;
  * Table 1: bold = best and underline = second best of each column over all seven rows, ranked on the printed
    values (ties share the mark); Table 2: bold = best over its eight rows, no underline;
  * clean seconds: median of the batch-1 timings at 4096^2 where a method was timed, otherwise "n/m";
  * Table 2 marks against 28-step SCA on every row but SCA itself (gen_prog_tables.py's rules):
    per-image metrics from <method>_vs_sca_nb.csv (2000 draws): + if ci_low > 0, circ if the interval includes
    zero, none if ci_high < 0; FID and patch FID (lower is better) from corrected_fidp_ci: + if ci_high < 0,
    circ if the interval includes zero, none if ci_low > 0;
  * Table 3: \\dn{} (orange) if the 95% interval lies below zero, \\up{} if above (the caption says none is);
  * Table 4: signed paired differences; every row has a paired CSV with a 95% interval, and a cell is set in
    \\dn{} (orange) when that interval lies below zero, i.e. the row is significantly worse than its reference;
  * shading: default SCA in Tables 1 to 3 and progressive SCA in Table 2.
After writing, the script checks the prompt counts and the qualitative claims printed next to these numbers;
if one fails it lists it and exits with status 1 (the files are still written).
"""
