def paired_file(rel, method, reference):
    out, ns = {}, set()
    for r in rows(rel):
        assert (r["method"], r["reference"]) == (method, reference), (rel, r)
        ns.add(int(r["n_prompts"]))
        out[r["metric"]] = (float(r["delta"]), float(r["ci_low"]), float(r["ci_high"]))
    assert len(ns) == 1, (rel, ns)
    return out, ns.pop()


