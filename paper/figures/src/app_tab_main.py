    lines.append("    \\midrule")
    lines.append("    \\multicolumn{9}{@{}l}{\\emph{HRGen-1K, 1000 prompts without references: AReA's Table~2 and our "
                 "FLUX.1-Krea-dev run}} \\\\")
    for r in hrows:
        lines.append("    " + row_tex(B, r, hbest, COLS, 1000))
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}"]
    runs = [SWITCH[("krea", "sca_krea")], SWITCH[("dev", "sca_nb")], SWITCH[("hrgen_krea", "sca_krea")]]
