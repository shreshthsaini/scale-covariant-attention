"""Ideogram 4 at 8192^2 table (tab:ideogram4): SCA minus each baseline, per-image metrics with 95% paired intervals,
and per-image cost. Reads only results/ideogram4_8k (scripts/ideogram4_eval.py); writes snippets/ideogram4.tex.

Columns: SCA vs. full attention and vs. SEGA (always), vs. NTK and vs. YaRN when their pairs exist (3 prompts, kept
in the table with their prompt count so the reader sees the smaller sample). Rows: the project's ten per-image
metrics, with MUSIQ on a 4096 px downscale (pyiqa's full-resolution MUSIQ does not fit at 8192^2; MUSIQ_c is unchanged:
four 1024^2 native crops), then median seconds per image and peak memory from the sidecars (timing_summary.csv).
Cell rule as src/gen_prog_tables.py: \\up / \\dn when the interval excludes zero in favour of / against SCA.
Run with the sca env python from paper/figures/src:  <python> gen_ideogram4_table.py
"""
import argparse
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent.parent
RESULTS = PAPER.parent / "results" / "ideogram4_8k"
SNIPPET = PAPER / "figures" / "snippets" / "ideogram4.tex"
METRICS = [("ir", "ImageReward", 1, 3), ("aesthetic", "Aesthetic", 1, 3), ("clip", "CLIP score", 1, 2),
           ("pickscore", "PickScore", 1, 2), ("hpsv2", r"HPSv2 ($\times100$)", 100, 2),
           ("hpsv21", r"HPSv2.1 ($\times100$)", 100, 2), ("musiq_4096", r"MUSIQ (4096 px)", 1, 1),
           ("musiq_crop1024", r"MUSIQ$_\text{c}$", 1, 1), ("clipiqa", r"CLIP-IQA ($\times100$)", 100, 1),
           ("arniqa", r"ARNIQA ($\times100$)", 100, 1)]
BASELINES = [("full", "full attention"), ("sega", "SEGA"), ("ntk", "NTK"), ("yarn", "YaRN")]
NAMES = {"sca": r"\sca{}", "full": "full attention", "sega": "SEGA", "ntk": "NTK", "yarn": "YaRN"}


def signed(x, d):
    s = f"{x:+.{d}f}"
    if float(s) == 0:
        s = ("-" if x < 0 else "+") + s[1:]
    return s.replace("-", "{-}") if s.startswith("-") else s


def cell(v, scale, d):
    delta, lo, hi = (x * scale for x in v)
    body = f"${signed(delta, d)}$"
    if lo > 0:
        body = r"\up{" + body + "}"
    elif hi < 0:
        body = r"\dn{" + body + "}"
    return body + r" {\tiny[$" + signed(lo, d) + "$, $" + signed(hi, d) + "$]}"


def pairs(results, b):
    path = results / f"sca_vs_{b}.csv"
    if not path.exists():
        return None, 0
    out, n = {}, set()
    for r in csv.DictReader(open(path)):
        assert (r["method"], r["reference"], r["res"]) == ("sca", b, "8192x8192"), r
        out[r["metric"]] = (float(r["delta"]), float(r["ci_low"]), float(r["ci_high"]))
        n.add(int(r["n_prompts"]))
    assert len(n) == 1, (path, n)
    return out, n.pop()


def timing(results):
    rows = {r["method"]: r for r in csv.DictReader(open(results / "timing_summary.csv")) if r["res"] == "8192x8192"}
    return rows


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--results", type=Path, default=RESULTS)
    p.add_argument("--out", type=Path, default=SNIPPET)
    a = p.parse_args(argv)
    cols = []
    for b, name in BASELINES:
        d, n = pairs(a.results, b)
        if d is not None:
            cols.append((b, name, d, n))
    if [c[0] for c in cols[:2]] != ["full", "sega"]:
        raise SystemExit("need results/ideogram4_8k/sca_vs_full.csv and sca_vs_sega.csv")
    t = timing(a.results)
    head = " & ".join([r"Metric"] + [rf"vs.\ {name} ($n={n}$)" for _, name, _, n in cols])
    body = []
    for key, label, scale, dec in METRICS:
        if all(key in d for _, _, d, _ in cols):
            body.append(" & ".join([label] + [cell(d[key], scale, dec) for _, _, d, _ in cols]) + r" \\")
    methods = ["sca"] + [b for b, *_ in cols]
    sec = " & ".join(f"{NAMES[m]} {float(t[m]['median_seconds']) / 3600:.2f}" for m in methods if m in t)
    mem = " & ".join(f"{NAMES[m]} {float(t[m]['max_peak_memory_gb']):.0f}" for m in methods if m in t)
    ncols = 1 + len(cols)
    lines = [
        "% Generated by src/gen_ideogram4_table.py from results/ideogram4_8k; do not edit by hand.",
        r"\begin{table}[!htbp]",
        r"\caption{\textbf{Ideogram 4 at $8192^2$, twice its native $4096^2$.} Per-image differences (\sca{} minus each "
        r"baseline) with 95\% paired intervals over 2000 prompt draws, seed 0, prompts the two methods share; \up{blue} / "
        r"\dn{orange}: the interval excludes zero in favour of / against \sca{}. MUSIQ is computed on a 4096\,px "
        r"downscale and MUSIQ$_\text{c}$ on four $1024^2$ native crops. Cost: median GPU hours per image (both "
        r"transformers, 48 steps, VAE decode) and peak memory in GB on one GH200. Intervals that include zero do not "
        r"establish equivalence.}",
        r"\label{tab:ideogram4}",
        r"\centering\scriptsize\setlength{\tabcolsep}{2.4pt}\let\tiny\scriptsize",
        r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%",
        r"\begin{tabular}{l" + "c" * len(cols) + "}",
        r"\toprule", head + r" \\", r"\midrule", *body, r"\midrule",
        r"\multicolumn{%d}{l}{GPU hours per image: %s} \\" % (ncols, sec.replace(" & ", ", ")),
        r"\multicolumn{%d}{l}{Peak memory (GB): %s} \\" % (ncols, mem.replace(" & ", ", ")),
        r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    a.out.write_text("\n".join(lines))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
