#!/usr/bin/env python3
"""Appendix tables that switch to the final operator (sca_v2) as its evaluations land, generated from CSVs.

    PATH=$HOME/.local/bin:$PATH UV_CACHE_DIR=/work/09032/saini_2/vista/library/uv-cache uv run --no-project \\
        --python /work/09032/saini_2/vista/library/uv-envs/sca/bin/python python paper/figures/src/gen_app_tables.py
    ... gen_app_tables.py --check   # also compare the pending rendering with today's main.tex / snippets
    ... gen_app_tables.py --where   # print the main.tex line ranges each snippet replaces, and the \\input lines

Writes paper/figures/snippets/app_tables/<name>.tex, one per table, and app_tables/pending_notes.tex, the caption-note
macros (\\pendApp...; \\input once in the preamble). A note expands to v2swap.NOTE while any of its table's runs is
pending and to nothing once all have landed. Cells that will change show the published value as \\pend{value}.

Two snippet kinds:
  tabular  replaces the body of a hand-typed table in main.tex: every line after \\label{tab:...} up to the line
           before \\end{table} (font and \\tabcolsep lines, \\resizebox, the tabulars). Caption, label and float stay.
  float    a whole float that replaces an existing \\input{figures/snippets/<old>.tex} line.

The tables come from the group modules listed in MODULES; each exposes tables() -> list of dicts with keys
  name, kind ("tabular" | "float"), label (tab:...), old (float only: old snippet file name), runs (list of run
  names in v2swap.RUNS or v2swap.LATENCY), note (macro name or None), tex (snippet text), subs (list of
  (new, old) strings: intended differences from today's table, e.g. "w/o schedule" labels; undone by --check),
  warnings (list of str: claims in the caption that the current numbers no longer support).
--check needs every run pending (it sets SCA_V2_PENDING=1 itself) and exits 1 on a mismatch.
"""
from __future__ import annotations

import argparse
import difflib
import importlib
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

PAPER = HERE.parents[1]
MAIN = PAPER / "main.tex"
SNIPPETS = PAPER / "figures" / "snippets"
OUT = (Path(os.environ["SCA_V2_MOCK"]) / "snippets" / "app_tables") if os.environ.get("SCA_V2_MOCK") else \
    SNIPPETS / "app_tables"  # a mock run (v2swap.py --make-mock) never writes into paper/
MODULES = ("app_tab_main", "app_tab_phase2")
GENERATED = "% Generated by src/gen_app_tables.py"
FAILED = []


def collect(only=None):
    import traceback
    import v2swap
    tables, missing = [], []
    for name in MODULES:
        if only and name not in only:
            continue
        try:
            mod = importlib.import_module(name)
            built = mod.tables()
        except ModuleNotFoundError as err:
            if err.name != name:
                raise
            missing.append(name)
            continue
        except Exception:  # one broken group must not stop the others
            print(f"gen_app_tables: {name} FAILED\n" + traceback.format_exc())
            FAILED.append(name)
            continue
        for t in built:
            t.setdefault("subs", [])
            t.setdefault("warnings", [])
            t["pending"] = any(not v2swap.landed(r) for r in t["runs"])
            tables.append(t)
    names = [t["name"] for t in tables]
    if len(set(names)) != len(names):
        raise ValueError(f"duplicate table names {names}")
    return tables, missing


def write(tables):
    import v2swap
    OUT.mkdir(parents=True, exist_ok=True)
    for t in tables:
        text = t["tex"].rstrip("\n") + "\n"
        (OUT / f"{t['name']}.tex").write_text(text)
    notes = [GENERATED + "; \\input once in the preamble. Each \\pendApp... macro ends the caption of the named "
             "table:", "% while one of its runs is pending it adds the grey-values note, afterwards nothing."]
    for t in tables:
        if t["note"]:
            runs = ", ".join(t["runs"])
            notes.append(f"% {t['label']} ({t['name']}.tex): {runs}")
            notes.append(v2swap.note_macro(t["note"], t["pending"]))
    (OUT / "pending_notes.tex").write_text("\n".join(notes) + "\n")


# ------------------------------------------------------------- check / where ------------------------------------
def unwrap_pend(s):
    """Replace every \\pend{X} by X (balanced braces)."""
    out, i = [], 0
    while True:
        j = s.find(r"\pend{", i)
        if j < 0:
            out.append(s[i:])
            return "".join(out)
        out.append(s[i:j])
        k, depth = j + len(r"\pend{"), 1
        start = k
        while depth:
            depth += {"{": 1, "}": -1}.get(s[k], 0)
            k += 1
        out.append(s[start:k - 1])
        i = k


def normalize(text, t):
    import v2swap
    text = text.replace(v2swap.PEND_FALLBACK, "")
    if t["note"]:
        text = text.replace("\\" + t["note"], "")
    text = unwrap_pend(text)
    for new, old in t["subs"]:
        text = text.replace(new, old)
    lines = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("%"):
            continue
        lines.append(re.sub(r"\s+", " ", line))
    return lines


def region(t, tex_lines):
    """(first, last) 1-based main.tex lines a tabular snippet replaces."""
    hits = [i for i, l in enumerate(tex_lines) if f"\\label{{{t['label']}}}" in l]
    if len(hits) != 1:
        raise ValueError(f"{t['label']}: {len(hits)} labels in main.tex")
    i = hits[0] + 1
    j = i
    while "\\end{table}" not in tex_lines[j]:
        j += 1
    return i + 1, j


def input_line(t):
    return f"\\input{{figures/snippets/app_tables/{t['name']}.tex}}"


def where(tables):
    tex_lines = MAIN.read_text().splitlines()
    for t in tables:
        if t["kind"] == "tabular":
            a, b = region(t, tex_lines)
            print(f"{t['label']}: main.tex lines {a}-{b} -> {input_line(t)}")
        else:
            old = f"\\input{{figures/snippets/{t['old']}}}"
            hits = [i + 1 for i, l in enumerate(tex_lines) if l.strip() == old]
            print(f"{t['label']}: main.tex line {','.join(map(str, hits)) or '(not found)'} {old} -> {input_line(t)}")
    notes = [t["note"] for t in tables if t["note"]]
    print(f"preamble: \\input{{figures/snippets/app_tables/pending_notes.tex}}; caption ends: "
          + ", ".join("\\" + n for n in notes))


def check(tables):
    tex_lines = MAIN.read_text().splitlines()
    bad = 0
    for t in tables:
        if t["kind"] == "tabular":
            a, b = region(t, tex_lines)
            today = "\n".join(tex_lines[a - 1:b])
            src = f"main.tex {a}-{b}"
        else:
            today = (SNIPPETS / t["old"]).read_text()
            src = f"snippets/{t['old']}"
        want, got = normalize(today, {"note": None, "subs": []}), normalize(t["tex"], t)
        if want == got:
            print(f"check {t['name']}: identical to {src} (after unwrapping \\pend and {len(t['subs'])} label changes)")
            continue
        bad += 1
        print(f"check {t['name']}: DIFFERS from {src}")
        for line in list(difflib.unified_diff(want, got, "today", "generated", lineterm="", n=0))[:40]:
            print("    " + line[:300])
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="render every run as pending and compare with today")
    ap.add_argument("--where", action="store_true", help="print the main.tex replacements")
    ap.add_argument("--only", nargs="+", metavar="MODULE", help=f"restrict to these of {', '.join(MODULES)}")
    args = ap.parse_args()
    if args.check:
        os.environ["SCA_V2_PENDING"] = "1"
    tables, missing = collect(args.only)
    if missing:
        print(f"gen_app_tables: modules not found, skipped: {', '.join(missing)}")
    if args.check:
        sys.exit(1 if check(tables) or FAILED else 0)
    if args.only:  # keep the notes of the other modules: rebuild them too, quietly
        others, _ = collect([m for m in MODULES if m not in args.only])
        write(others + tables)
    else:
        write(tables)
    for t in tables:
        state = "pending" if t["pending"] else "landed"
        print(f"{t['name']}.tex ({t['label']}): {state} [{', '.join(t['runs']) or 'no runs'}]")
        for w in t["warnings"]:
            print(f"    WARNING {t['name']}: {w}")
    if args.where:
        where(tables)
    if FAILED:
        sys.exit(1)


if __name__ == "__main__":
    main()
