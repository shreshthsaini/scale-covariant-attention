"""Render an explicitly curated six-method portrait comparison from real outputs.

All methods use the same prior hero prompt and fixed crop coordinates. No metric
ranking selects this image. The provenance retains source and output hashes.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw
import imgsel

METHODS = [('full', 'Full attention'), ('dype', 'DyPE'),
           ('sega_official', 'SEGA'), ('area', 'AReA'),
           ('ultraimage', 'UltraImage$^*$'), ('sca', r'\textbf{SCA}')]
PROMPT = '3657338173664010496'
BOX = (1600, 1280, 2368, 2048)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    for method in ('dype', 'sega_official', 'ultraimage'):
        imgsel.ROOTS[method] = imgsel.OUT + '/main/' + method + '/{res}'
    destination = Path(imgsel.FIGDIR) / 'teaser_six'
    destination.mkdir(exist_ok=True)
    records = []
    for method, _ in METHODS:
        source = Path(imgsel.find(method, '4096x4096', PROMPT))
        sidecar = source.with_suffix('.json')
        meta = json.loads(sidecar.read_text())
        digest = sha(source)
        if meta.get('complete') is not True or meta.get('png_sha256') != digest:
            raise ValueError('Incomplete or hash-mismatched source: ' + str(source))
        with Image.open(source) as opened:
            image = opened.convert('RGB')
        if image.size != (4096, 4096):
            raise ValueError('Wrong resolution')
        crop = image.crop(BOX)
        full = image.resize((768, 768), Image.Resampling.LANCZOS)
        draw = ImageDraw.Draw(full)
        draw.rectangle(tuple(round(x * 768 / 4096) for x in BOX), outline='#D55E00', width=3)
        full_path, crop_path = destination / (method + '_full.jpg'), destination / (method + '_crop.jpg')
        full.save(full_path, quality=95, subsampling=0)
        crop.save(crop_path, quality=95, subsampling=0)
        records.append(dict(method=method, source=str(source), png_sha256=digest,
                            sidecar_sha256=sha(sidecar), config=meta['config'],
                            full_sha256=sha(full_path), crop_sha256=sha(crop_path)))
    (destination / 'provenance.json').write_text(json.dumps(dict(
        selection='Curated portrait already used in the prior SCA hero; no metric ranking.',
        prompt_id=records[0]['config']['prompt_id'], crop_xyxy=BOX,
        displayed_crop_size=[768, 768], records=records), indent=2) + '\n')
    rows = [' & '.join(label for _, label in METHODS) + r' \\']
    for kind in ('full', 'crop'):
        rows.append(' & '.join(r'\includegraphics[width=0.158\linewidth]{figures/teaser_six/'
                    + method + '_' + kind + '.jpg}' for method, _ in METHODS) + r' \\[-1pt]')
    text = '\n'.join([
        '% Generated by fig_teaser_six.py; sources and fixed crop recorded alongside images.',
        r'\begin{center}\begin{minipage}{\linewidth}\centering\sffamily\scriptsize',
        r'\setlength{\tabcolsep}{1.6pt}\begin{tabular}{@{}cccccc@{}}', *rows,
        r'\end{tabular}',
        r'\captionof{figure}{\textbf{Global composition and fine detail at $4096^2$.} '
        r'One curated evaluation prompt across six methods: full images above, identical '
        r'$768\times768$ crop coordinates below. The portrait and crop were already present '
        r'in our earlier hero selection. FLUX.1-dev and seed label 0; Full attention, DyPE, '
        r'SEGA, AReA and SCA share 28 steps and guidance 4.5. $^*$UltraImage uses its '
        r'two-stage defaults (30+30 steps). This example illustrates detail and artifacts; '
        r'aggregate comparisons and randomly selected galleries test broader behavior.}',
        r'\label{fig:teaser}\end{minipage}\end{center}', ''])
    (Path(imgsel.FIGDIR) / 'snippets/teaser_six.tex').write_text(text)


if __name__ == '__main__':
    main()
