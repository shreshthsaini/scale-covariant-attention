"""Late-arriving results (HRDiT on 191 prompts, E2 at 6144^2, E9 on FLUX.1-Krea-dev) as paper tables.

Every value comes from the archived CSVs under results/; nothing is typed by hand.
* figures/snippets/krea_6144.tex: Table tab:krea_6144, paired intervals at 6144^2 (SCA vs AReA, 100 prompts) and on
  FLUX.1-Krea-dev (SCA, DyPE, SEGA vs AReA, 100 prompts at 4096^2).
* main.tex, filled in place when the placeholder rows are still present, and verified on every run:
  the 6144^2 block of tab:all_metrics, the FLUX.1-Krea-dev row of tab:generality, and the HRDiT column of
  tab:phase2_baselines (results/hrdit191/hrdit_dev_author_vs_sca.csv).
Run: python gen_late_tables.py   (idempotent; fails loudly if main.tex disagrees with the CSVs)
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent.parent
RES = PAPER.parent / "results"
MAIN = PAPER / "main.tex"
SNIPPET = PAPER / "figures" / "snippets" / "krea_6144.tex"

# (metric, label, scale, decimals, higher_is_better)
PER_IMAGE = [("ir", "ImageReward", 1, 3, True), ("aesthetic", "Aesthetic", 1, 2, True),
             ("clip", "CLIP score", 1, 2, True), ("pickscore", "PickScore", 1, 2, True),
             ("hpsv2", r"HPSv2 ($\times100$)", 100, 2, True), ("hpsv21", r"HPSv2.1 ($\times100$)", 100, 2, True),
             ("musiq", "MUSIQ", 1, 1, True), ("musiq_crop", r"MUSIQ$_\text{c}$", 1, 1, True),
             ("clipiqa", r"CLIP-IQA ($\times100$)", 100, 1, True), ("arniqa", r"ARNIQA ($\times100$)", 100, 1, True)]
DIST = [("fid", r"FID$\downarrow$", 1, 1, False), ("kid", r"KID$\downarrow$ ($\times10^3$)", 1000, 2, False),
        ("patch_fid", r"FID$_\text{p}\downarrow$", 1, 1, False),
        ("patch_kid", r"KID$_\text{p}\downarrow$ ($\times10^3$)", 1000, 2, False),
        ("is", "Inception score", 1, 2, True), ("seconds", r"Time (s)$\downarrow$", 1, 1, False)]


def norm(metric):
    return "musiq_crop" if metric == "musiq_crop1024" else metric


def load_deltas(folder, method, reference="area", n="100", setlevel=None):
    """Paired deltas (method minus reference) from eval.py / eval_extra.py; with `setlevel`, FID, KID and their patch
    versions come from that corrected-crop, reference-cluster bootstrap CSV instead (repro/evaluate_corrected.py)."""
    out = {}
    names = [RES / folder / "base_paired_deltas.csv", RES / folder / "extra_paired_deltas.csv"]
    for path in names + ([RES / folder / setlevel] if setlevel else []):
        for r in csv.DictReader(open(path)):
            if r["method"] == method and r["reference_method"] == reference:
                key = norm(r["metric"])
                if setlevel and path in names and key in {"fid", "kid", "patch_fid", "patch_kid"}:
                    continue
                assert r["delta_definition"] == "method_minus_reference" and r["n_prompts"] == n, r
                assert r["ci_low"] != "" and r["ci_high"] != "", f"missing interval {folder} {method} {r['metric']}"
                out[key] = (float(r["value"]), float(r["ci_low"]), float(r["ci_high"]))
    if setlevel:
        assert {"fid", "kid", "patch_fid", "patch_kid"} <= set(out), (folder, sorted(out))
    return out


KREA195 = (RES / "krea195" / "corrected_fidp_ci" / "paired_deltas.csv").exists()


def load_summary(folder):
    out = {}
    for name in ("base_summary.csv", "extra_summary.csv"):
        for r in csv.DictReader(open(RES / folder / name)):
            out[(r["method"], norm(r["metric"]))] = float(r["value"])
    return out


def signed(x, d):
    s = f"{x:+.{d}f}"
    return "{-}" + s[1:] if s.startswith("-") else s


def cell(v, scale, d, higher):
    delta, lo, hi = (x * scale for x in v)
    body = f"${signed(delta, d)}$"
    good, bad = (lo > 0, hi < 0) if higher else (hi < 0, lo > 0)
    if good:
        body = r"\up{" + body + "}"
    elif bad:
        body = r"\dn{" + body + "}"
    return body + r" {\tiny[$" + signed(lo, d) + "$, $" + signed(hi, d) + "$]}"


def better(v, higher):
    _, lo, hi = v
    return lo > 0 if higher else hi < 0


def krea_6144_table():
    cols = [("e2_6144", "sca_nb", r"\sca{}"), ("e9_krea", "sca_krea", r"\sca{}"), ("e9_krea", "dype", "DyPE"),
            ("e9_krea", "sega_official", "SEGA")]
    data = [load_deltas(f, m) for f, m, _ in cols]
    if KREA195:  # SCA on all 195 Krea prompts; DyPE and SEGA keep the 100 prompts they ran
        cols[1] = ("krea195", "sca_krea", r"\sca{}")
        data[1] = load_deltas("krea195", "sca_krea", n="195", setlevel="corrected_fidp_ci/paired_deltas.csv")
    lines = [r"% Generated by src/gen_late_tables.py from results/e2_6144, results/e9_krea and results/krea195; do not edit by hand.",
             r"\begin{table}[!htbp]",
             r"\caption{\textbf{At $6144^2$ \sca{} beats AReA on 14 of 15 metrics; on FLUX.1-Krea-dev it wins six "
             r"metrics and loses ImageReward and patch FID, in a third of the time.} Method minus AReA with 95\% paired intervals over " + ("100 prompts at $6144^2$ and for DyPE and SEGA, which ran only those, and all 195 for \\sca{} on FLUX.1-Krea-dev; first column " if KREA195 else "100 prompts each; first column ") +
             r"FLUX.1-dev at $6144^2$, others FLUX.1-Krea-dev at $4096^2$ with a Krea-calibrated \sca{} table. Per-image "
             r"intervals use 1000 prompt draws; FID, KID, and their patch versions resample prompts and reference-image "
             r"clusters. Lower is better for FID, KID, their patch versions, and time. \up{Blue} / \dn{orange}: "
             r"significantly better / worse than AReA. Time is the campaign mean on shared GH200 nodes.}",
             r"\label{tab:krea_6144}",
             r"\centering\scriptsize\setlength{\tabcolsep}{2.4pt}\let\tiny\scriptsize",
             r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%",
             r"\begin{tabular}{lcccc}", r"\toprule",
             r" & $6144^2$ & \multicolumn{3}{c}{FLUX.1-Krea-dev, $4096^2$} \\", r"\cmidrule(lr){2-2}\cmidrule(l){3-5}",
             "Metric & " + " & ".join(c[2] for c in cols) + r" \\", r"\midrule"]
    for key, label, scale, d, higher in PER_IMAGE + DIST:
        lines.append(label + " & " + " & ".join(cell(x[key], scale, d, higher) for x in data) + r" \\")
        if key == "arniqa":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    SNIPPET.write_text("\n".join(lines))
    wins = sum(better(data[0][k], h) for k, _, _, _, h in PER_IMAGE + DIST if k != "seconds")
    print(f"wrote {SNIPPET}; 6144^2 SCA significantly better than AReA on {wins} of 15 metrics")
    krea = data[1]
    print("Krea SCA vs AReA:", {k: ("+" if better(krea[k], h) else ("-" if better((-krea[k][0], -krea[k][2],
                                                                                   -krea[k][1]), h) else "0"))
                                for k, _, _, _, h in PER_IMAGE + DIST})
    return data


def fmt_row(s, method, base, marks, bold):
    """One tab:all_metrics row at 6144^2: Lat, IR, Aesth, CLIP, Pick, HPSv2, HPSv2.1, FID, FIDp, MUSIQ, MUSIQc,
    CLIP-IQA, ARNIQA (HPS, CLIP-IQA, ARNIQA x100)."""
    spec = [("seconds", 1, 1), ("ir", 1, 2), ("aesthetic", 1, 2), ("clip", 1, 2), ("pickscore", 1, 2),
            ("hpsv2", 100, 2), ("hpsv21", 100, 2), ("fid", 1, 1), ("patch_fid", 1, 1), ("musiq", 1, 1),
            ("musiq_crop", 1, 1), ("clipiqa", 100, 1), ("arniqa", 100, 1)]
    cells = []
    for key, scale, d in spec:
        v = s[(method, key)] * scale
        txt = f"{v:.{d}f}"
        txt = f"${txt}$" if v < 0 else txt
        if bold.get(key):
            txt = r"\textbf{" + txt + "}"
        if key == "seconds":
            txt += r"\rlap{$^\ddagger$}"
        elif marks.get(key):
            txt += marks[key]
        cells.append(txt)
    return f"    {base} & " + " & ".join(cells) + r" \\"


def all_metrics_6144(data):
    s = load_summary("e2_6144")
    d = data[0]
    lower = {"seconds", "fid", "patch_fid"}
    keys = ["seconds", "ir", "aesthetic", "clip", "pickscore", "hpsv2", "hpsv21", "fid", "patch_fid", "musiq",
            "musiq_crop", "clipiqa", "arniqa"]
    best = {k: ("sca_nb" if (s[("sca_nb", k)] < s[("area", k)]) == (k in lower) else "area") for k in keys}
    marks = {}
    for k in keys:
        if k == "seconds":
            continue
        _, lo, hi = d[k]
        marks[k] = r"\sg" if (lo > 0 if k not in lower else hi < 0) else (r"\sw" if (hi < 0 if k not in lower
                                                                                        else lo > 0) else "")
    area = fmt_row(s, "area", "AReA (released code)", {}, {k: best[k] == "area" for k in keys})
    sca = fmt_row(s, "sca_nb", r"\sca{} (final)", marks, {k: best[k] == "sca_nb" for k in keys})
    return area, sca


def generality_krea(data):
    v = data[1]
    return (r"    FLUX.1-Krea-dev & 100 & AReA & $" + signed(v["ir"][0], 3) + "$ & $" + signed(100 * v["hpsv21"][0], 2)
            + "$ & $" + signed(v["musiq_crop"][0], 2) + r"$ \\")


def hrdit_column():
    rows = {}
    for r in csv.DictReader(open(RES / "hrdit191" / "hrdit_dev_author_vs_sca.csv")):
        assert (r["method"], r["reference"], r["n_prompts"], r["res"]) == ("hrdit_dev_author", "sca_nb", "191",
                                                                          "4096x4096"), r
        rows[norm(r["metric"])] = (float(r["delta"]), float(r["ci_low"]), float(r["ci_high"]))
    return {label: cell(rows[k], scale, d, h) for k, label, scale, d, h in PER_IMAGE}


def replace_once(text, old, new, what):
    if new in text:
        return text
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"{what}: expected one placeholder, found {n}")
    print("filled", what)
    return text.replace(old, new)


def main():
    data = krea_6144_table()
    tex = MAIN.read_text()
    area, sca = all_metrics_6144(data)
    tbd13 = " & ".join([r"\tbd"] * 13)
    tex = replace_once(tex, f"    AReA (released code) & {tbd13} \\\\\n    \\sca{{}} (final) & {tbd13} \\\\",
                       area + "\n" + sca, "tab:all_metrics 6144^2 rows")
    tex = replace_once(tex, r"\emph{$6144\times6144$}, scale factors (6, 6), 100 prompts \todo{E2}} \\",
                       r"\emph{$6144\times6144$}, scale factors (6, 6), 100 prompts} \\", "6144 block header")
    krea = generality_krea(data)
    tex = replace_once(tex, r"    FLUX.1-Krea-dev & \tbd & AReA & \tbd & \tbd & \tbd \\", krea, "tab:generality Krea row")
    # HRDiT column of tab:phase2_baselines
    start = tex.index(r"\label{tab:phase2_baselines}")
    end = tex.index(r"\end{table}", start)
    block = tex[start:end]
    if "HRDiT" not in block:
        col = hrdit_column()
        new = block.replace(r"\begin{tabular}{lccc}", r"\begin{tabular}{lcccc}", 1)
        new = new.replace(r"Metric & DyPE & SEGA & UltraImage \\", r"Metric & DyPE & SEGA & UltraImage & HRDiT \\", 1)
        for label, c in col.items():
            pat = re.compile(r"^(" + re.escape(label) + r" & .*?) \\\\$", re.M)
            new, n = pat.subn(lambda m: m.group(1) + " & " + c + r" \\", new, count=1)
            assert n == 1, label
        tex = tex[:start] + new + tex[end:]
        print("filled tab:phase2_baselines HRDiT column")
    MAIN.write_text(tex)
    # verification of what is now in main.tex
    for row in (area, sca, krea):
        assert row in tex, row
    block = tex[tex.index(r"\label{tab:phase2_baselines}"):]
    block = block[:block.index(r"\end{table}")]
    for label, c in hrdit_column().items():
        assert re.search(re.escape(c) + r" \\\\", block), label
    print("main.tex rows verified against results/e2_6144, results/e9_krea, results/hrdit191")


if __name__ == "__main__":
    main()
