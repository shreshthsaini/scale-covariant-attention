"""Data of the speed chart (SCAComp.speed, web/assets/js/c_speed.js): seconds per image against image side.

Everything comes from the paper's Figure 7 loader, paper/figures/src/v6_scaling.py (load, derived, checks), which
reads results/latency_curve_v2/summary.csv (single-pass SCA), results/latency_curve_summary.csv and the audited
results/latency_curve.csv (AReA and full attention), results/latency_curve_batch1.csv (full attention at 6144^2) and
results/prog_latency/latency_summary.csv (progressive SCA and HRDiT, 4096^2 only), and checks every value against
the paper's tables and macros (tab:latency, \\hlSecSca, \\hlSpeedArea, the exponents 0.99 and 1.12, ...). The build
runs those checks and stops if any fails. Nothing is typed.
  lines   single-pass SCA, AReA, full attention: clean batch-1 median of three timed images at each side, with the
          fastest and slowest of the three; full attention was not run at 8192^2
  points  progressive SCA and HRDiT at 4096^2 (sweep 3)
  ratio   AReA's median over single-pass SCA's at each side (the per-size speed-up the paper prints to 2 decimals)
  prog    AReA over progressive SCA at 4096^2, both from sweep 3 (\\hlSpeedProgArea), and HRDiT over progressive SCA
  expo    fitted exponent b of seconds proportional to N^b (N image tokens), per line
Seconds print half up to 0.1 s as the paper does.

Run (repository root, CPU, seconds):
  /work/09032/saini_2/vista/library/uv-envs/sca/bin/python web/build/v5_build_speed.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.dirname(HERE)
REPO = os.path.dirname(WEB)
sys.path.insert(0, os.path.join(REPO, "paper", "figures", "src"))

import v6_scaling as vs  # noqa: E402

OUT = os.path.join(WEB, "assets", "data", "speed")


def main():
    os.makedirs(OUT, exist_ok=True)
    cells, area3 = vs.load()
    expo, ratio = vs.derived(cells)
    vs.checks(cells, area3, expo, ratio)               # the paper's own checks; exits on a mismatch
    prog = cells["sca_v2_prog", 4096]["med"]

    def c(m, s):
        x = cells[m, s]
        return dict(s=s, med=round(x["med"], 3), lo=round(x["lo"], 3), hi=round(x["hi"], 3), t=f"{vs.half_up(x['med']):.1f}")
    lines = []
    for m in ("sca_v2", "area", "full"):
        lines.append(dict(id=m, label=vs.NAME[m], expo=f"{expo[m]:.2f}",
                          pts=[c(m, s) for s in vs.SIDES if (m, s) in cells]))
    rec = dict(
        sides=list(vs.SIDES), tokens={str(s): vs.tokens(s) for s in vs.SIDES}, lines=lines,
        points=[dict(id=m, label=vs.NAME[m], **c(m, 4096)) for m in ("sca_v2_prog", "hrdit_dev_author")],
        ratio={str(s): round(ratio[s], 4) for s in vs.SIDES},
        ratio_t={str(s): f"{ratio[s]:.2f}" for s in vs.SIDES},
        prog=dict(area=f"{area3 / prog:.1f}", hrdit=f"{cells['hrdit_dev_author', 4096]['med'] / prog:.1f}",
                  area_t=f"{vs.half_up(area3):.1f}"),
        missing=[dict(id="full", s=8192, why="not run")],
        source=dict(script="web/build/v5_build_speed.py", loader="paper/figures/src/v6_scaling.py",
                    note="one GH200, batch 1, text encoding and VAE decoding included, one warm-up image excluded"))
    with open(os.path.join(OUT, "data.js"), "w") as f:
        f.write("/* Generated by web/build/v5_build_speed.py; do not edit. */\n")
        f.write("window.SCA_DATA = window.SCA_DATA || {};\n")
        f.write("window.SCA_DATA.speed = " + json.dumps(rec, separators=(",", ":")) + ";\n")
    for ln in lines:
        print(ln["label"], ln["expo"], [(p["s"], p["t"]) for p in ln["pts"]])
    print("points", [(p["label"], p["t"]) for p in rec["points"]], "ratio", rec["ratio_t"], "prog", rec["prog"])


if __name__ == "__main__":
    main()
