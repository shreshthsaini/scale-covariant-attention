#!/usr/bin/env python3
"""Data for the page's concept chart: one switch for every head (AReA) against one calibrated mix per head (SCA).

The web version of paper Figure 2 (paper/figures/concept.pdf, drawn by paper/figures/src/fig_concept.py). Input is the
figure's own data file, results/heads_view/concept_curves.csv: one row per (layer, head, sigma) on a fixed grid of 80
noise levels from the gate (0.89) down to 0.10, column pi (the weight each of FLUX.1-dev's 1,368 heads puts on its
native window at ratio 4, as the sampler reads the scale-4 table), and mean_after_gate (the head's mean over the grid,
which sets its colour). Output: web/assets/js/concept.js, window.SCA_CONCEPT with

  sigma      the 80 noise levels, in CSV order
  pi_b64     the 1,368 x 80 weights, head-major, each rounded to a byte (pi * 255) for drawing only
  mean       each head's mean_after_gate as the CSV stores it (6 decimals): its colour and the hover readout
  median     the median over heads at every sigma, 4 decimals (np.median, as fig_concept.py draws it)
  gate       the gate sigma (the first grid value, 0.89)
  blocks, heads_per_block   the grid of heads (heads are stored block-major, as the CSV sorts them)

The bytes only position lines on the canvas (1/255 of the axis is under a pixel at the page's chart size); no number
the page prints comes from them, and the hover readout prints only block, head and the exact mean. Run with the sca
env python from anywhere:
  /work/09032/saini_2/vista/library/uv-envs/sca/bin/python web/build/build_concept.py
"""
from __future__ import annotations

import base64
import csv
import hashlib
import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
CSV = REPO / "results" / "heads_view" / "concept_curves.csv"
OUT = REPO / "web" / "assets" / "js" / "concept.js"


def main() -> None:
    heads: dict[tuple[int, int], list[tuple[float, float]]] = {}
    mean: dict[tuple[int, int], float] = {}
    with open(CSV, newline="") as fh:
        for r in csv.DictReader(fh):
            key = (int(r["layer"]), int(r["head"]))
            heads.setdefault(key, []).append((float(r["sigma"]), float(r["pi"])))
            mean[key] = float(r["mean_after_gate"])
    keys = sorted(heads)
    sigma = [s for s, _ in heads[keys[0]]]
    if any([s for s, _ in heads[k]] != sigma for k in keys):
        raise ValueError(f"{CSV}: heads do not share one sigma grid")
    Y = np.array([[p for _, p in heads[k]] for k in keys])           # [heads, sigma]
    m = np.array([mean[k] for k in keys])
    if Y.min() < 0 or Y.max() > 1 or m.min() < 0 or m.max() > 1:
        raise ValueError("pi outside [0, 1]")
    if not np.allclose(Y.mean(axis=1), m, atol=1e-5):
        raise ValueError("mean_after_gate is not the mean of the head's curve")
    blocks, per = max(k[0] for k in keys) + 1, max(k[1] for k in keys) + 1
    if keys != [(b, h) for b in range(blocks) for h in range(per)]:
        raise ValueError(f"{CSV}: heads do not form a full blocks x heads grid")
    med = np.median(Y, axis=0)
    q = np.rint(Y * 255).astype(np.uint8)
    data = dict(source=str(CSV.relative_to(REPO)), sha256=hashlib.sha256(CSV.read_bytes()).hexdigest(),
                n_heads=len(keys), blocks=blocks, heads_per_block=per, n_sigma=len(sigma), gate=sigma[0],
                sigma=[round(s, 6) for s in sigma],
                median=[round(float(x), 4) for x in med],
                pi_b64=base64.b64encode(q.tobytes()).decode("ascii"),
                mean=[round(float(x), 6) for x in m],
                n_mean_below_0_3=int((m < 0.3).sum()), n_mean_above_0_9=int((m > 0.9).sum()))
    OUT.write_text("// Generated by web/build/build_concept.py from results/heads_view/concept_curves.csv; do not "
                   "edit.\nwindow.SCA_CONCEPT = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(keys)} heads x {len(sigma)} sigma values, "
          f"{OUT.stat().st_size / 1024:.0f} KB; median {med.min():.3f} to {med.max():.3f}")


if __name__ == "__main__":
    main()
