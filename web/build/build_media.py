"""List the page's rendered videos in web/assets/js/media.js (window.SCA_MEDIA), so the page shows a video only when
its file exists and a labelled placeholder otherwise (no 404s from file://).

Videos (made by other scripts in web/build):
  teaser/zoom_loop.mp4, stages_loop.mp4 (render_process_videos.py), teaser/heads_loop.mp4 (render_explainer.py),
  each with a .webp poster of the same name; method/sca_explainer.mp4 with _poster.webp and .vtt (render_explainer.py).
Run after any of them changes: python web/build/build_media.py
"""
import json
import os

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(WEB, "assets", "video")


def rel(p):
    return os.path.relpath(p, WEB).replace(os.sep, "/")


def entry(mp4, poster=None, vtt=None):
    if not os.path.exists(mp4) or os.path.getsize(mp4) == 0:
        return None
    e = {"mp4": rel(mp4), "bytes": os.path.getsize(mp4)}
    if poster and os.path.exists(poster):
        e["poster"] = rel(poster)
    if vtt and os.path.exists(vtt):
        e["vtt"] = rel(vtt)
    return e


def main():
    media = {"teaser": {}}
    for key in ("zoom", "stages", "heads"):
        e = entry(os.path.join(V, "teaser", f"{key}_loop.mp4"), os.path.join(V, "teaser", f"{key}_loop.webp"))
        if e:
            media["teaser"][key] = e
    e = entry(os.path.join(V, "method", "sca_explainer.mp4"), os.path.join(V, "method", "sca_explainer_poster.webp"),
              os.path.join(V, "method", "sca_explainer.vtt"))
    if e:
        media["explainer"] = e
    out = os.path.join(WEB, "assets", "js", "media.js")
    with open(out, "w") as f:
        f.write("// Generated by web/build/build_media.py; do not edit.\n")
        f.write("window.SCA_MEDIA = " + json.dumps(media, indent=1) + ";\n")
    print(out, json.dumps(media))


if __name__ == "__main__":
    main()
