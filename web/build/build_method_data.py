"""Data for the interactive method figures of the project page: assets/js/method_data.js.

Reads (read only)
  /scratch/09032/saini_2/sca/calib/k1_1024.npz (falls back to paper/figures/src/data/k1_1024_pi.npz for the tables):
      s2_pi_head, s4_pi_head [57 blocks, 24 heads, 14 noise bins], sigma_centers, populated, and the sufficient
      statistics `stats` [2 ratios, 6, 57, 24, 14] with A, B, E, F at indices 0, 1, 2, 4 (F normalises the error).
  results/heads_view/rings.csv: attention mass of three heads at 1024^2 in Chebyshev rings around the query
      (the data of the paper's head figure, panel b).
Writes
  web/assets/js/method_data.js: window.SCA_METHOD = {table: per-head weights at ratios 2 and 4 on the populated
      bins as base64 bytes (value * 255, rounded; for drawing only), order (heads of each block sorted by their
      ratio-4 weight at the middle bin, as in the paper), examples: A, B, E, F of the three ring heads at both ratios
      (exact float64 values, so the page draws the exact error parabola), rings}.
Run (repository root, CPU, seconds):
  /work/09032/saini_2/vista/library/uv-envs/sca/bin/python web/build/build_method_data.py
"""
import base64
import csv
import hashlib
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
NPZ = "/scratch/09032/saini_2/sca/calib/k1_1024.npz"
RINGS = os.path.join(REPO, "results", "heads_view", "rings.csv")
OUT = os.path.join(REPO, "web", "assets", "js", "method_data.js")
MID_BIN = 7  # the paper sorts heads within each block by the weight at this bin


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    z = np.load(NPZ, allow_pickle=True)
    scales = [int(s) for s in z["scales"]]
    pop = np.asarray(z["populated"], bool)
    sig = np.asarray(z["sigma_centers"], float)
    bins = np.flatnonzero(pop)
    tables = {}
    for r in (2, 4):
        pi = np.asarray(z[f"s{r}_pi_head"], float)  # [57, 24, 14]
        assert pi.shape == (57, 24, 14)
        sel = pi[:, :, bins]
        assert np.all(np.isfinite(sel)) and sel.min() >= 0 and sel.max() <= 1
        b = np.rint(sel * 255).astype(np.uint8)  # [57, 24, nb], row-major: block, head, bin
        tables[f"r{r}"] = base64.b64encode(b.tobytes()).decode()
    order = np.argsort(z["s4_pi_head"][:, :, MID_BIN], axis=1, kind="stable").tolist()

    rings = {}
    with open(RINGS) as f:
        for row in csv.DictReader(f):
            d = rings.setdefault(row["role"], {"block": int(row["block"]), "head": int(row["head"]),
                                               "bin": int(row["bin"]), "rings": []})
            d["rings"].append({k: (float(row[k]) if k in ("share", "density_vs_uniform", "opacity") else int(row[k]))
                               for k in ("ring", "cheb_from", "cheb_to", "tokens", "share", "density_vs_uniform", "opacity")})

    stats = np.asarray(z["stats"], float)  # [2, 6, 57, 24, 14]
    examples = []
    for role in ("local", "mid", "global"):
        if role not in rings:
            continue
        l, h, b = rings[role]["block"], rings[role]["head"], rings[role]["bin"]
        ex = {"role": role, "block": l, "head": h, "bin": b, "sigma": float(sig[b])}
        for r in (2, 4):
            S = stats[scales.index(r)]
            A, B, E, F = (float(S[i, l, h, b]) for i in (0, 1, 2, 4))
            pistar = 1.0 if A == 0 else min(max(B / A, 0.0), 1.0)
            stored = float(z[f"s{r}_pi_head"][l, h, b])
            assert abs(pistar - stored) < 1e-6, (role, r, pistar, stored)
            ex[f"r{r}"] = {"A": A, "B": B, "E": E, "F": F, "pistar": pistar}
        examples.append(ex)

    data = {
        "source": {"npz": NPZ, "npz_sha256": sha(NPZ), "rings": "results/heads_view/rings.csv",
                   "rings_sha256": sha(RINGS)},
        "blocks": 57, "heads": 24, "sigma": [round(float(s), 4) for s in sig[bins]], "mid": int(np.flatnonzero(bins == MID_BIN)[0]),
        "table": tables, "order": order, "examples": examples, "rings": rings,
    }
    with open(OUT, "w") as f:
        f.write("// Generated by web/build/build_method_data.py from the per-head table and results/heads_view/rings.csv; do not edit.\n")
        f.write("window.SCA_METHOD = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes): {len(bins)} bins, examples "
          + ", ".join(f"{e['role']} b{e['block']} h{e['head']} pi*(r4)={e['r4']['pistar']:.3f}" for e in examples))


if __name__ == "__main__":
    main()
