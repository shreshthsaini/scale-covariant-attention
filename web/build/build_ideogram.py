"""Ingest Ideogram 4.0 images for the "Against a commercial model" section.

Usage (from the repo root, sca env python):
    python web/build/build_ideogram.py            # convert dropped files, refresh the manifest and its JS mirror
    python web/build/build_ideogram.py --init     # (re)create the manifest skeleton from compare_selection.json

Drop each image as web/assets/ideogram/<prompt_id>.{png,jpg,jpeg,webp}. PNG and JPEG files are converted to
WebP (quality 92, original pixels, no resizing) and the original is moved to
/scratch/09032/saini_2/sca/web_assets/ideogram_originals/. The manifest web/build/ideogram_manifest.json keeps one
entry per prompt: prompt id and text, source, resolution (filled from the file), whether the image was upscaled,
the licence note, an optional crop centre and the one-line verdict shown under the pair. The page reads
web/assets/js/ideogram_manifest.js (written here) when opened from file://, and the JSON itself over http.
No image is ever fabricated: an entry without a file renders as a labelled placeholder.
"""
import glob
import json
import os
import shutil
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.normpath(os.path.join(HERE, ".."))
MANIFEST = os.path.join(HERE, "ideogram_manifest.json")
DROP = os.path.join(WEB, "assets", "ideogram")
ORIG = "/scratch/09032/saini_2/sca/web_assets/ideogram_originals"
PROMPTS = ["2232973817337527860", "m8737279395568207187", "5849277588805396896",
           "m8343371271909676658", "997293625843621481", "m548913239957610051"]
LICENCE = ("Generated by the authors with Ideogram 4.0 from the prompt text above; not an official Ideogram "
           "sample. Ideogram's Terms of Service (ideogram.ai/legal/tos) assign rights in user outputs to the user. "
           "Record here the plan, the date and any upscaling used.")


def init():
    sel = json.load(open(os.path.join(HERE, "compare_selection.json")))
    by = {it["sid"]: it for it in sel["items"]}
    items = [dict(prompt_id=p, prompt=by[p]["prompt"], file="assets/ideogram/%s.webp" % p,
                  source="Ideogram 4.0 (app or API), highest resolution offered, same prompt text, no other edits",
                  resolution=None, upscaled=None, generated_on=None, licence_note=LICENCE,
                  crop_center=None, verdict="") for p in PROMPTS]
    man = dict(schema=1, model="Ideogram 4.0",
               note="Fill source, upscaled, generated_on and verdict by hand; resolution is read from the file.",
               items=items)
    json.dump(man, open(MANIFEST, "w"), indent=1)
    print("wrote", MANIFEST)


def ingest():
    man = json.load(open(MANIFEST))
    os.makedirs(DROP, exist_ok=True)
    for e in man["items"]:
        pid = e["prompt_id"]
        webp = os.path.join(DROP, pid + ".webp")
        for src in sorted(glob.glob(os.path.join(DROP, pid + ".*"))):
            ext = os.path.splitext(src)[1].lower()
            if ext in (".png", ".jpg", ".jpeg"):
                Image.open(src).convert("RGB").save(webp, "WEBP", quality=92, method=6)
                os.makedirs(ORIG, exist_ok=True)
                shutil.move(src, os.path.join(ORIG, os.path.basename(src)))
                print("converted", src)
        if os.path.exists(webp):
            e["resolution"] = list(Image.open(webp).size)
            e["status"] = "present"
        else:
            e["resolution"] = None
            e["status"] = "missing"
        print(pid, e["status"], e["resolution"])
    json.dump(man, open(MANIFEST, "w"), indent=1)
    with open(os.path.join(WEB, "assets", "js", "ideogram_manifest.js"), "w") as fh:
        fh.write("// Generated by web/build/build_ideogram.py from web/build/ideogram_manifest.json.\n")
        fh.write("window.SCA_IDEOGRAM = " + json.dumps(man, indent=1) + ";\n")


if __name__ == "__main__":
    if "--init" in sys.argv or not os.path.exists(MANIFEST):
        init()
    ingest()
