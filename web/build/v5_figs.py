#!/usr/bin/env python3
"""The paper's v6 vector plots as theme-aware SVG for the page.

Reads paper/figures/v6/<stem>.svg (written by paper/figures/src/v6_*.py; never edited here) and writes
  web/assets/img/v6/<stem>.svg   the light figure as printed (metadata stripped), used by <img> and <noscript>
  web/assets/js/v6_figs.js       window.SCA_FIGS = {stem: {svg, w, h, alt}}: the same SVG with every paper colour
                                 replaced by the page's CSS variable, so one file follows the light and dark themes.
The colour map is fixed below (paper palette in paper/figures/src/sca_colors.tex); an unmapped colour stops the
build. Element ids get a per-figure prefix so several figures can sit inline on one page.

Usage: /work/09032/saini_2/vista/library/uv-envs/sca/bin/python web/build/v5_figs.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "paper" / "figures" / "v6"
OUT_IMG = REPO / "web" / "assets" / "img" / "v6"
OUT_JS = REPO / "web" / "assets" / "js" / "v6_figs.js"

FIGS = {
    "quality_time": "ImageReward on 195 prompts against clean seconds per 4096 squared image on one GH200: progressive "
                    "SCA is the fastest point and sits level with HRDiT, above AReA.",
    "gains": "Paired differences of progressive and single-pass SCA from AReA over their per-prompt standard "
             "deviation, with 95% intervals, for every metric.",
    "scaling": "Clean seconds per image against image side for single-pass SCA, AReA and full attention, both axes "
               "logarithmic.",
    "latency": "Seconds per image against image side, with the speed-up over full attention.",
    "baseline_deltas": "Paired differences of progressive SCA from every baseline, per metric, with 95% intervals.",
}
COLOURS = {   # paper hex -> page token (light values in design.md)
    "#1f2328": "var(--ink)",
    "#000000": "var(--ink)",
    "#ffffff": "var(--fig-bg, var(--bg))",
    "#5b6570": "var(--ink-soft)",
    "#56626f": "var(--ink-soft)",
    "#e3e6ea": "var(--rule)",
    "#e6e9ec": "var(--rule)",
    "#c3c9cf": "var(--rule)",
    "#13865f": "var(--accent)",
    "#9ad3ba": "var(--accent-soft)",
    "#d7eee4": "var(--accent-soft)",
    "#7a4ea3": "var(--area)",
    "#e9e0f1": "var(--area-soft)",
    "#9aa3ac": "var(--neutral)",
    "#828e9a": "var(--neutral)",
    "#7f7f7f": "var(--neutral)",
    "#cfcfcf": "var(--rule)",
    "#b85c00": "var(--worse)",
    "#0072b2": "var(--better)",
    "#2f6db3": "var(--far)",
    "#e08a2b": "var(--near)",
}
HEX = re.compile(r"#[0-9a-fA-F]{6}\b")


def clean(svg: str) -> str:
    svg = re.sub(r"<\?xml[^>]*\?>\s*", "", svg)
    svg = re.sub(r"<!DOCTYPE[^>]*>\s*", "", svg)
    svg = re.sub(r"<metadata>.*?</metadata>\s*", "", svg, flags=re.S)
    return svg.strip()


def themed(svg: str, stem: str) -> str:
    unknown = sorted({h.lower() for h in HEX.findall(svg)} - set(COLOURS))
    if unknown:
        raise SystemExit(f"{stem}.svg: unmapped colour(s) {', '.join(unknown)}; add them to COLOURS")
    svg = HEX.sub(lambda m: COLOURS[m.group(0).lower()], svg)
    ids = set(re.findall(r'\sid="([^"]+)"', svg))
    for i in sorted(ids, key=len, reverse=True):
        svg = svg.replace(f'id="{i}"', f'id="{stem}-{i}"').replace(f'href="#{i}"', f'href="#{stem}-{i}"')
        svg = svg.replace(f"url(#{i})", f"url(#{stem}-{i})")
    # scale with the container: keep the viewBox, drop the fixed point size
    svg = re.sub(r'<svg([^>]*?)\swidth="[^"]+"\s+height="[^"]+"', r'<svg\1', svg, count=1)
    return svg


def main() -> None:
    OUT_IMG.mkdir(parents=True, exist_ok=True)
    out = {}
    for stem, alt in FIGS.items():
        p = SRC / f"{stem}.svg"
        if not p.exists():
            print(f"skip {stem}: {p.relative_to(REPO)} missing")
            continue
        raw = clean(p.read_text(encoding="utf-8"))
        vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', raw)
        w, h = float(vb.group(1)), float(vb.group(2))
        (OUT_IMG / f"{stem}.svg").write_text(raw + "\n", encoding="utf-8")
        t = themed(raw, stem)
        t = t.replace("<svg ", f'<svg role="img" aria-label="{alt}" preserveAspectRatio="xMidYMid meet" ', 1)
        out[stem] = {"svg": t, "w": w, "h": h, "alt": alt}
        print(f"{stem}: {w:g} x {h:g} pt, {len(t) / 1024:.1f} KB inline")
    OUT_JS.write_text("// Generated by web/build/v5_figs.py from paper/figures/v6/*.svg; do not edit.\n"
                      "window.SCA_FIGS = " + json.dumps(out, ensure_ascii=True) + ";\n", encoding="utf-8")
    print(f"wrote {OUT_JS.relative_to(REPO)} ({OUT_JS.stat().st_size / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
