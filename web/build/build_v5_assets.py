#!/usr/bin/env python3
"""Tell the page which v5 components and videos exist, so it loads only real files (no 404s, works from file://).

Scans web/assets/js/c_<name>.js (+ web/assets/css/c_<name>.css) written by the interactive-components owner and
web/assets/video/v5/manifest.json written by the media owner, and writes web/assets/js/v5_assets.js:
    window.SCA_V5 = {comps: {name: {js, css}}, videos: {role: {file, poster, width, height, seconds, loop, alt, ...}}}
A manifest entry is used only when its file (and poster, if named) exist under web/; paths are made relative to web/.
Entries without a "role" are listed under videos by their file stem. Rerun after either owner adds files:

    /work/09032/saini_2/vista/library/uv-envs/sca/bin/python web/build/build_v5_assets.py
"""
from __future__ import annotations

import json
from pathlib import Path

WEB = Path(__file__).resolve().parents[1]
OUT = WEB / "assets" / "js" / "v5_assets.js"
MANIFEST = WEB / "assets" / "video" / "v5" / "manifest.json"
KEEP = ("file", "poster", "width", "height", "seconds", "loop", "alt", "caption", "vtt", "role",
        "readout", "prompt", "still", "label", "model", "size", "seed", "title")   # what the pages read; provenance stays in the manifest


def rel(p: str | None, base: Path) -> str | None:
    """A manifest path as a path relative to web/ (accepts web-relative, manifest-relative or absolute paths)."""
    if not p:
        return None
    cands = [WEB / p, base / p, Path(p)]
    for c in cands:
        try:
            c = c.resolve()
            if c.exists() and WEB.resolve() in c.parents:
                return c.relative_to(WEB.resolve()).as_posix()
        except OSError:
            continue
    return None


def main() -> None:
    comps = {}
    for js in sorted((WEB / "assets" / "js").glob("c_*.js")):
        name = js.stem[2:]
        css = WEB / "assets" / "css" / f"c_{name}.css"
        comps[name] = {"js": f"assets/js/{js.name}", "css": f"assets/css/{css.name}" if css.exists() else None}
    videos, skipped = {}, []
    if MANIFEST.exists():
        data = json.loads(MANIFEST.read_text(encoding="utf-8"))
        items = data if isinstance(data, list) else data.get("videos") or data.get("items") or [
            dict(v, role=v.get("role") or k) for k, v in data.items() if isinstance(v, dict)]
        for it in items:
            if not isinstance(it, dict):
                continue
            f = rel(it.get("file") or it.get("mp4"), MANIFEST.parent)
            if not f:
                skipped.append(str(it.get("file") or it.get("mp4")))
                continue
            e = {k: it[k] for k in KEEP if k in it}
            if it.get("role") not in ("hero16x9", "hero9x16"):
                e.pop("readout", None)          # only the hero draws a readout; keeps the registry small
            e["file"] = f
            if it.get("poster"):
                e["poster"] = rel(it["poster"], MANIFEST.parent)
            if it.get("vtt"):
                e["vtt"] = rel(it["vtt"], MANIFEST.parent)
            if it.get("still"):
                e["still"] = rel(it["still"], MANIFEST.parent)
            role = it.get("role") or Path(f).stem
            e["role"] = role
            key = role if role not in videos else f"{role}_{Path(f).stem}"   # several items may share a role (formation)
            videos[key] = e
    OUT.write_text("// Generated by web/build/build_v5_assets.py; do not edit. Which v5 components and videos exist.\n"
                   "window.SCA_V5 = " + json.dumps({"comps": comps, "videos": videos}, ensure_ascii=True, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"wrote {OUT.relative_to(WEB.parent)}: {len(comps)} component(s) {sorted(comps)}, {len(videos)} video(s) "
          f"{sorted(videos)}" + (f"; skipped (file missing): {skipped}" if skipped else ""))


if __name__ == "__main__":
    main()
