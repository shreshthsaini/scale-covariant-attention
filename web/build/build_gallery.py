"""The page's fixed-rule gallery: the first N prompts of the 195-prompt Aesthetic-4K evaluation set, in the order of
results/evidence/prompts/aesthetic4k_eval.jsonl, at seed label 0: progressive SCA beside AReA at 4096^2.

No image is chosen by hand: the prompts are the first N of the file and the 1:1 crop is the central 512 x 512 native
window of every image.

Outputs: web/assets/img/gallery/<sid>_{prog,area}.webp (1280 px), <sid>_prog_thumb.webp (560 px),
<sid>_{prog,area}_crop.webp (native 1:1 centre crop) and web/assets/js/gallery.js (window.SCA_GALLERY).
Run (repository root, CPU, about a minute with 6 processes):
  nice -n 19 /work/09032/saini_2/vista/library/uv-envs/sca/bin/python web/build/build_gallery.py [--n 12]
"""
import argparse
import glob
import hashlib
import json
import os
from multiprocessing import Pool

from PIL import Image

Image.MAX_IMAGE_PIXELS = None
HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.dirname(HERE)
REPO = os.path.dirname(WEB)
PROMPTS = os.path.join(REPO, "results", "evidence", "prompts", "aesthetic4k_eval.jsonl")
OUT = "/scratch/09032/saini_2/sca/out"
SRC = {"prog": OUT + "/dupfix_prog/sca_v2_prog/4096x4096", "area": OUT + "/main/area/4096x4096"}
IMG = os.path.join(WEB, "assets", "img", "gallery")
VIEW, THUMB, CROP = 1280, 560, 512


def short(pid):
    s = pid.replace("a4k_eval_4096_", "")
    return "m" + s[5:] if s.startswith("minus") else s


def png(method, pid):
    hits = sorted(glob.glob(f"{SRC[method]}/{pid}_*_seed0.png"))
    if len(hits) != 1:
        raise FileNotFoundError(f"{method} {pid}: {hits}")
    return hits[0]


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rel(p):
    return os.path.relpath(p, WEB).replace(os.sep, "/")


def one(job):
    sid, method, src = job
    im = Image.open(src).convert("RGB")
    W, H = im.size
    rec = {"source_png": src, "png_sha256": sha(src), "size": [W, H]}
    v = im.resize((VIEW, round(VIEW * H / W)), Image.LANCZOS)
    p = os.path.join(IMG, f"{sid}_{method}.webp")
    v.save(p, "WEBP", quality=78, method=6)
    rec["view"] = rel(p)
    x, y = (W - CROP) // 2, (H - CROP) // 2
    p = os.path.join(IMG, f"{sid}_{method}_crop.webp")
    im.crop((x, y, x + CROP, y + CROP)).save(p, "WEBP", quality=86, method=6)
    rec["crop"] = rel(p)
    rec["box"] = [x, y, CROP]
    if method == "prog":
        p = os.path.join(IMG, f"{sid}_prog_thumb.webp")
        v.resize((THUMB, round(THUMB * H / W)), Image.LANCZOS).save(p, "WEBP", quality=76, method=6)
        rec["thumb"] = rel(p)
    return sid, method, rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=12)
    ap.add_argument("--procs", type=int, default=6)
    a = ap.parse_args()
    rows = [json.loads(l) for l in open(PROMPTS)][: a.n]
    os.makedirs(IMG, exist_ok=True)
    jobs = [(short(r["id"]), m, png(m, r["id"])) for r in rows for m in SRC]
    with Pool(a.procs) as pool:
        out = pool.map(one, jobs)
    recs = {}
    for sid, m, rec in out:
        recs.setdefault(sid, {})[m] = rec
    items = [{"sid": short(r["id"]), "index": i + 1, "prompt": r["prompt"], "img": recs[short(r["id"])]}
             for i, r in enumerate(rows)]
    data = {"rule": f"the first {a.n} prompts of the {sum(1 for _ in open(PROMPTS))}-prompt Aesthetic-4K evaluation set, seed 0",
            "prompts_file": rel(PROMPTS).replace("../", ""), "crop_rule": "central 512 x 512 native pixels",
            "methods": {"prog": "Progressive SCA", "area": "AReA"}, "items": items}
    js = os.path.join(WEB, "assets", "js", "gallery.js")
    with open(js, "w") as f:
        f.write("// Generated by web/build/build_gallery.py; do not edit.\n")
        f.write("window.SCA_GALLERY = " + json.dumps(data, indent=1) + ";\n")
    total = sum(os.path.getsize(os.path.join(IMG, f)) for f in os.listdir(IMG))
    print(f"wrote {js}; {len(items)} prompts; images {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
